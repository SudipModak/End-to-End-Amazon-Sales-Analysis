#Q8. Compare total revenue generated by Online vs Offline sales channels. Which performs better?


select distinct Sales_Channel, round(sum(Total_Revenue),2) as Online_vs_Offline from amazon_sales group by Sales_Channel order by Online_vs_Offline desc;

---------------------------------------------------------------------------------------------------------------------------------------------------------
#Q9.Identify the top 5 countries with the highest total profit.

Select Country, round(sum(Total_Profit),0) as Countrywise_Profit from amazon_sales  group by Country order by Countrywise_Profit asc limit 5;

