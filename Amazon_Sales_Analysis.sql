create database amazonedb;
use amazonedb;
CREATE TABLE amazon_sales (
    Region VARCHAR(50),
    Country VARCHAR(50),
    Item_Type VARCHAR(50),
    Sales_Channel VARCHAR(20),
    Order_Priority VARCHAR(5),
    Order_Date DATE,
    Order_ID BIGINT,
    Ship_Date DATE,
    Units_Sold INT,
    Unit_Price FLOAT,
    Unit_Cost FLOAT,
    Total_Revenue FLOAT,
    Total_Cost FLOAT,
    Total_Profit FLOAT
);
select * from amazon_sales;
---------------------------------------------------------------------------------------------------------------
#Q1. What is the total revenue generated across all orders?

select round(sum(Total_Revenue),2)as Total_Revenue_across_all_orders from amazon_sales;

---------------------------------------------------------------------------------------------
#Q2.Which item type has generated the highest total profit?

SELECT 
    Item_Type,
    ROUND(SUM(Total_Revenue), 2) AS Total_Revenue_itemwise
FROM amazon_sales
GROUP BY Item_Type
ORDER BY Total_Revenue_itemwise DESC
LIMIT 1;

---------------------------------------------------------------------------------------------
#Q3. Which region contributes the most to overall revenue? Rank regions from highest to lowest.

select Region , round(Sum(Total_Revenue),2) as Total_regionwise_revenue from amazon_sales group by Region order by Total_regionwise_revenue desc;

---------------------------------------------------------------------------------------------------------------------
#Q4. What is the month-wise sales trend (total revenue per month)?

SELECT 
    MONTHNAME(Order_Date) AS Order_Month,
    Region,
    ROUND(SUM(Total_Revenue), 2) AS Month_Wise_Sales
FROM amazon_sales
GROUP BY 
    Order_Month, 
    Region
ORDER BY 
    Month_Wise_Sales Asc;

-----------------------------------------------------------------------------------------------
#Q5. What is the average shipping duration (in days), and which region has the highest delay?
 SELECT 
    Region,
    round(AVG(DATEDIFF(Ship_Date, Order_Date)),0) AS avg_shipping_time
FROM amazon_sales
GROUP BY Region
ORDER BY avg_shipping_time DESC;

