#Q6.Which country has the highest number of units sold overall?

select Country,round(sum(Unit_Price),2) as Countrywise_Unit_sold from amazon_sales group by Country order by CountryWise_Unit_sold desc;

----------------------------------------------------------------------------------------------------------------------------------------------
#Q7.What is the profit margin (%) for each item type, and which is the most profitable category?

SELECT 
    Item_Type,
    ROUND((SUM(Total_Profit) / SUM(Total_Revenue)) * 100, 2) AS Profit_Percentage_Itemwise
FROM amazon_sales
GROUP BY Item_Type
ORDER BY Profit_Percentage_Itemwise DESC;

